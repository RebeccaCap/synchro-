// Creates server/config.php with a hashed admin password and a random secret.
// Usage: npm run setup-admin
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const readline = require("readline");

const ITERATIONS = 210000;
const outFile = path.join(__dirname, "..", "server", "config.php");

// One shared interface, so piped or pasted input isn't lost between questions.
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  terminal: Boolean(process.stdin.isTTY),
});
let muted = false;
rl._writeToOutput = (text) => {
  if (!muted) rl.output.write(text);
};
const lines = rl[Symbol.asyncIterator]();

async function askHidden(question) {
  process.stdout.write(question);
  muted = true;
  const { value = "" } = await lines.next();
  muted = false;
  process.stdout.write("\n");
  return value;
}

function exitWith(message) {
  console.error(message);
  rl.close();
  process.exit(1);
}

(async () => {
  const password = await askHidden("New admin password: ");
  if (password.length < 12) exitWith("Use at least 12 characters.");
  const confirm = await askHidden("Repeat password: ");
  rl.close();
  if (password !== confirm) exitWith("Passwords do not match.");

  const salt = crypto.randomBytes(16);
  const hash = crypto.pbkdf2Sync(password, salt, ITERATIONS, 32, "sha256");
  const secret = crypto.randomBytes(32).toString("hex");

  const config = `<?php
// Generated by \`npm run setup-admin\`. Upload to public_html/synchro-private/config.php.
// Do not commit this file.

return [
    'admin_password_hash' => 'pbkdf2$sha256$${ITERATIONS}$${salt.toString("hex")}$${hash.toString("hex")}',
    'secret' => '${secret}',
    'max_upload_mb' => 512,
];
`;

  fs.writeFileSync(outFile, config);
  console.log(`Wrote ${path.relative(process.cwd(), outFile)}`);
  console.log("Upload it to public_html/synchro-private/config.php on the server (see README).");
})();
